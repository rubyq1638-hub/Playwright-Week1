//Number – a whole number or decimal value
var height = 152.1;
console.log(height);
console.log(typeof height);

// String – text written using quotes or backticks
var myName = `Ruby Queen`;
console.log(myName);
console.log(typeof myName);

// Boolean – a value of true or false
var attendance = true;
console.log(attendance);
console.log(typeof attendance);

//BigInt – a large integer written with the n suffix
var price1 = 676897897897897987n;
console.log(price1);
console.log(typeof price1);

//Undefined – a declared variable with no assigned value
var date;
console.log(date);
console.log(typeof date);

//Null – an intentional absence of a value
var age = null;
console.log(age);
console.log(typeof age);